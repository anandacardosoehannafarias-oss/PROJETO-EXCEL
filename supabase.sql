-- Estrutura usada pelo index.html no Supabase (já aplicada no projeto "Excel Project").
create table public.gp_registros (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  store text not null check (store in ('professores','editais','alunos','projetos')),
  dados jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index gp_registros_user_store_idx on public.gp_registros (user_id, store);
alter table public.gp_registros enable row level security;
create policy "gp_registros_dono" on public.gp_registros for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create table public.gp_rascunho (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  dados jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.gp_rascunho enable row level security;
create policy "gp_rascunho_dono" on public.gp_rascunho for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('relatorios','relatorios',false,26214400,array['application/pdf']) on conflict (id) do nothing;
create policy "relatorios_dono_select" on storage.objects for select to authenticated
  using (bucket_id='relatorios' and (storage.foldername(name))[1]=(select auth.uid())::text);
create policy "relatorios_dono_insert" on storage.objects for insert to authenticated
  with check (bucket_id='relatorios' and (storage.foldername(name))[1]=(select auth.uid())::text);
create policy "relatorios_dono_delete" on storage.objects for delete to authenticated
  using (bucket_id='relatorios' and (storage.foldername(name))[1]=(select auth.uid())::text);
